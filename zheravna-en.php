        <h3>Main Attractions in Zheravna</h3>

        <h4>Architectural and Historical Reserve</h4>
        <p>Zheravna is an open-air museum of National Revival architecture — stone and wooden houses with rich wood carvings,
            narrow cobblestone streets, and numerous public fountains carefully preserved through the centuries.</p>

        <h4>St. Nicholas Church</h4>
        <p>A church built in 1834, featuring preserved icons and church artifacts
            from the 18th–19th centuries — an outstanding example of the region’s spiritual heritage.</p>

        <h4>House Museums</h4>
        <p>Zheravna is home to several notable museums, including:</p>
        <p>The house-museum of writer Yordan Yovkov (born here) — showcasing exhibits from his life and literary work.</p>
        <p>The houses of Sava Filaretov and Rusi Chorbadzhi — presenting National Revival lifestyle, crafts, and culture.</p>
        <p>An art gallery housed in the former primary school building,
            displaying works by local and nationally recognized artists.</p>

        <h4>International Folklore Costume Festival</h4>
        <p>Every August, Zheravna becomes the stage for a unique three-day festival,
            recreating Bulgarian folk dances, music, and traditional costumes — an event that attracts thousands of visitors.</p>

