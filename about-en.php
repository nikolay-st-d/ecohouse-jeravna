    <h2>About Eco House Zheravna – Detailed Information</h2>

<p><em><strong>Guest House</strong> Eco House ZHERAVNA is located in the village of the same name, 16 km from the town of Kotel. It offers accommodation for up to 13 guests in a restored and renovated National Revival house with a 300-year history. A unique combination of the spirit of the past and the luxury of the present!</em></p>

<img src="images/about1.jpg" alt="Eco House Zheravna">

<p><strong>Eco House “ZHERAVNA”</strong> was opened on May 8, 2003. It is rated three stars (***). This typical Zheravna-style house is a listed monument of culture and architecture, located on the main tourist street in the center of the village, which is an architectural reserve.</p>

<p><strong>The house</strong> is a two-storey building with a traditional layout and a 300-year history. After its restoration and conversion into a hotel, it has become a unique example in Bulgaria of the harmony between the spirit of the past and the luxury of the present.</p>

<p><strong>The guest rooms</strong> number five: one double room, one double room with an extra bed, two triple rooms, and one triple studio. Each room is designed in a style that blends comfort and luxury with folklore and authentic local character. Every room has a private bathroom, minibar, safe for valuables, TV with satellite channels (Bulsatcom), and fully preserved architectural details with handmade elements and wood carvings. Free Wi-Fi Internet access is available to all guests.</p>

<p>On the <strong>ground floor</strong> there are two guest rooms, a service room, and a traditional Zheravna-style common living room with an authentic interior, a fireplace with live fire, and a large raised seating area (mensofa) — an ideal place for gatherings, conversations, and shared meals.</p>

<p>On the <strong>upper floor</strong> there are three of the five guest rooms, a spacious veranda with a coffee corner, and an open summer sleeping area (mensofa).</p>

<p><strong>Heating</strong> is provided by a local central heating system. The guest house also has autonomous power supply, ensuring electricity when needed.</p>

<img src="images/about2.jpg" alt="Courtyard of Eco House Zheravna">

<p><strong>Service</strong> is available 24 hours a day. The small staff house is located next to the main guest house and is its stylistic counterpart. Guests can enjoy a spacious terraced courtyard, decorated in traditional folklore style with unique antique items characteristic of the National Revival period, a traditional Zheravna oven, a barbecue area, a small rock garden, and an open-air dining and relaxation space. An <strong>equipped kitchen</strong> is available for guests to prepare their own meals at no extra charge.</p>

<p><strong>The road infrastructure</strong> is good. In winter, roads are regularly cleared. Reliable GSM coverage is available for all mobile operators.</p>

<p><strong>The climate</strong> is mountainous and considered beneficial for respiratory, gastrointestinal, and cardiovascular conditions.</p>

<img src="images/about3.jpg" alt="Small reservoir near Zheravna">

<p><strong>Leisure activities</strong> include excursions to the town of Kotel, the ancient village of Katunishte, and the “Blue Pool” area near the village of Medven, as well as fishing at the small reservoir close to the village. Angling enthusiasts can try their luck for trout in the Kotel River, and for perch and pike-perch in the nearby natural lake “Skala.” Within a one-day trip, guests can also visit the larger reservoirs of Ticha (~75 km) and Kamchiya (~60 km), where species such as carp, pike-perch, crucian carp, roach, chub, barbel, catfish, perch, and others can be found. The surrounding forests are easily accessible and rich in plant and animal species, mushrooms, and herbs. Horse riding and hiking along organized eco-trails are also available.</p>

<p><strong>The village itself</strong> offers several traditional taverns, a permanent exhibition in the art gallery, and a collection of icons from the 16th, 17th, and 18th centuries housed in the church building, which is itself an architectural and cultural monument of European significance. Other attractive tourist sites include the house-museums of Yordan Yovkov, Sava Filaretov, and Rusi Chorbadzhi, the latter hosting the ethnographic exhibition of the local museum complex.</p>

